# By default, the input() function returns a string value

a = input("Enter your input: ")
print(type(a),a)

# We can convert the input to a different data type
b = int(input("Enter your input: "))
print(type(b),b)

# We can also use float() to convert the input to a float data type
c = float(input("Enter your input: "))
print(type(c),c) 

